#!/usr/bin/env node
/**
 * Reads data/category-aliases.json and writes a Supabase migration that
 * expands the category alias dictionary.
 */
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const inputFile = join(root, "data", "category-aliases.json");
const outputFile = join(
  root,
  "supabase",
  "migrations",
  "20260601100000_expand_category_aliases.sql",
);

const KNOWN_SLUGS = [
  "produce",
  "dairy",
  "meat_fish",
  "bakery",
  "frozen",
  "pantry",
  "beverages",
  "snacks",
  "household",
  "general",
];

const VALID_LANGUAGES = new Set(["en", "de", "fr", "nl", "da", "sv", "no", "fi"]);

function normalizeAlias(alias) {
  return alias.trim().toLowerCase().replace(/\s+/g, " ");
}

function escapeSql(value) {
  return value.replace(/'/g, "''");
}

function dedupeKey(alias, language) {
  return `${alias}\0${language ?? ""}`;
}

const raw = JSON.parse(await readFile(inputFile, "utf8"));

if (!Array.isArray(raw)) {
  throw new Error("category-aliases.json must be a JSON array");
}

const issues = [];
const seen = new Set();
const entries = [];

for (let i = 0; i < raw.length; i++) {
  const row = raw[i];
  const index = i + 1;

  if (!row || typeof row !== "object") {
    issues.push(`Row ${index}: expected object`);
    continue;
  }

  const { alias, slug, language } = row;

  if (typeof alias !== "string" || !alias.trim()) {
    issues.push(`Row ${index}: invalid alias`);
    continue;
  }

  if (typeof slug !== "string" || !KNOWN_SLUGS.includes(slug)) {
    issues.push(`Row ${index}: unknown slug "${slug}"`);
    continue;
  }

  if (language !== null && (typeof language !== "string" || !VALID_LANGUAGES.has(language))) {
    issues.push(`Row ${index}: invalid language "${language}"`);
    continue;
  }

  const normalized = normalizeAlias(alias);
  if (!normalized) {
    issues.push(`Row ${index}: alias normalizes to empty string`);
    continue;
  }

  const key = dedupeKey(normalized, language);
  if (seen.has(key)) {
    continue;
  }
  seen.add(key);

  entries.push({ alias: normalized, slug, language });
}

if (issues.length > 0) {
  console.error("Validation issues:");
  for (const issue of issues) {
    console.error(`  - ${issue}`);
  }
  process.exit(1);
}

const bySlug = new Map();
for (const slug of KNOWN_SLUGS) {
  bySlug.set(slug, []);
}
for (const entry of entries) {
  bySlug.get(entry.slug).push(entry);
}

const slugOrder = KNOWN_SLUGS.filter((slug) => bySlug.get(slug).length > 0);

let sql = `-- Provisionly v1.1: expand category alias dictionary
-- Generated by scripts/bundle-aliases.mjs — do not edit by hand
-- Total aliases: ${entries.length}

`;

for (const slug of slugOrder) {
  const rows = bySlug.get(slug);
  const valueLines = rows
    .map((row) => {
      const langSql = row.language === null ? "null" : `'${row.language}'`;
      return `    ('${escapeSql(row.alias)}', ${langSql})`;
    })
    .join(",\n");

  sql += `-- ${slug} (${rows.length})\n`;
  sql += `insert into public.category_aliases (alias_normalized, category_id, language)\n`;
  sql += `select v.alias, c.id, v.lang\n`;
  sql += `from public.categories c\n`;
  sql += `cross join (\n`;
  sql += `  values\n${valueLines}\n`;
  sql += `) as v(alias, lang)\n`;
  sql += `where c.slug = '${slug}'\n`;
  sql += `on conflict (alias_normalized, language) do nothing;\n\n`;
}

await writeFile(outputFile, sql);

const counts = Object.fromEntries(
  slugOrder.map((slug) => [slug, bySlug.get(slug).length]),
);

console.log(`Wrote ${outputFile}`);
console.log(`Total aliases: ${entries.length}`);
console.log("By slug:", counts);
